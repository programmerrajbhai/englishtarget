  static List<BasicSentence> _makeSentences(
      String prefix,
      List<String> lines,
      Color color,
      ) {
    return <BasicSentence>[
      for (int index = 0; index < lines.length; index++)
        _makeSentence(
          prefix: prefix,
          index: index,
          line: lines[index],
          color: color,
        ),
    ];
  }

  static BasicSentence _makeSentence({
    required String prefix,
    required int index,
    required String line,
    required Color color,
  }) {
    final List<String> parts = line.split('||');

    return BasicSentence(
      id: '${prefix}_${index + 1}',
      bengali: parts[0].trim(),
      english: parts[1].trim(),
      visualKey: '${prefix}_${index + 1}',
      icon: _sentenceIcons[index % _sentenceIcons.length],
      color: color,
    );
  }

